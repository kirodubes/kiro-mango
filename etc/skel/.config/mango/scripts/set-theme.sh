#!/usr/bin/env bash
#####################################################################
# Author    : Erik Dubois
# Website   : https://kiroproject.be
#####################################################################
#   DO NOT JUST RUN THIS. EXAMINE AND JUDGE. RUN AT YOUR OWN RISK.
#
# Purpose:
#   Generate a colour palette from the current wallpaper with pywal and fan it
#   out to the Kiro mango desktop: waybar (colors.css), mako, and mango's window
#   borders (config.conf, 0xRRGGBBAA). Reloads waybar + mako; mango border
#   colours apply on the next `reload_config` (Super+Shift+R) or login.
# Why:
#   The edition's theming engine — one wallpaper drives every colour.
#   Re-theme: set-theme.sh ~/Pictures/some.jpg
#####################################################################

set -euo pipefail

WALLPAPER="${1:-$HOME/.config/mango/bg/kiro.jpg}"
CACHE="$HOME/.cache/wal/colors.sh"
WAYBAR_COLORS="$HOME/.config/waybar/colors.css"
MAKO_CONFIG="$HOME/.config/mako/config"
MANGO_CONF="$HOME/.config/mango/config.conf"

command -v wal >/dev/null 2>&1 || { echo "pywal (wal) not installed — skipping theme"; exit 0; }
[ -f "$WALLPAPER" ] || { echo "Wallpaper not found: $WALLPAPER"; exit 0; }

wal -i "$WALLPAPER" -n -q
# shellcheck source=/dev/null
source "$CACHE"   # exports $background $foreground $color0 … $color15

# ── waybar ────────────────────────────────────────────────────────────────────
cat > "$WAYBAR_COLORS" <<EOF
/* Generated by set-theme.sh (pywal) from ${WALLPAPER##*/}. */
@define-color bg      ${background};
@define-color fg      ${foreground};
@define-color muted   ${color8};
@define-color accent  ${color4};
@define-color accent2 ${color5};
@define-color info    ${color6};
@define-color good    ${color2};
@define-color warn    ${color3};
@define-color crit    ${color1};
EOF

# ── mako ──────────────────────────────────────────────────────────────────────
if [ -f "$MAKO_CONFIG" ]; then
    sed -i \
        -e "s|^background-color=.*|background-color=${background}|" \
        -e "s|^text-color=.*|text-color=${foreground}|" \
        -e "s|^border-color=.*|border-color=${color4}|" \
        "$MAKO_CONFIG"
fi

# ── mango borders (config.conf, 0xRRGGBBAA) ──────────────────────────────────
if [ -f "$MANGO_CONF" ]; then
    sed -i \
        -e "s|^rootcolor=.*|rootcolor=0x${background#\#}ff|" \
        -e "s|^bordercolor=.*|bordercolor=0x${color8#\#}ff|" \
        -e "s|^focuscolor=.*|focuscolor=0x${color4#\#}ff|" \
        -e "s|^urgentcolor=.*|urgentcolor=0x${color1#\#}ff|" \
        "$MANGO_CONF"
fi

# ── Reload live surfaces ──────────────────────────────────────────────────────
pkill -SIGUSR2 waybar 2>/dev/null || true
makoctl reload 2>/dev/null || true
# mango re-reads config.conf on Super+Shift+R (reload_config) — no reliable CLI.

echo "Theme applied from ${WALLPAPER##*/}"
